TOKEN_RE = re.compile(r"[А-ЯA-Z]+(?:-[А-ЯA-Z]+)*")


def tokens(text: str) -> list[str]:
    return TOKEN_RE.findall((text or "").upper().replace("Ё", "Е"))


def department_region(code: str | None) -> str | None:
    """«500-050» → «50»; бывшие автономные округа приводятся к нынешнему субъекту."""
    d = re.sub(r"\D", "", code or "")
    if len(d) != 6:
        return None
    r = MERGED.get(d[:2], d[:2])
    return r if r in REGIONS else None


def region_name(code: str) -> str:
    return REGIONS[code][0] if code in REGIONS else code


@lru_cache(maxsize=None)
def _city_forms() -> dict[str, str]:
    out = {}
    for code, (_, _, cap) in REGIONS.items():
        if not cap:
            continue
        forms = {cap}
        if cap.endswith("Ь"):
            b = cap[:-1]
            forms |= {b + "И", b + "Ю", b + "Е"}
        elif cap.endswith(("А", "Я")):
            b = cap[:-1]
            forms |= {b + "Ы", b + "И", b + "Е", b + "У", b + "ОЙ"}
        elif cap.endswith(("ЫЙ", "ИЙ")):
            b = cap[:-2]
            forms |= {b + "ОГО", b + "ОМ", b + "ОМУ"}
        elif cap[-1] not in "ОЕЫИУЭ":
            forms |= {cap + "А", cap + "Е", cap + "У", cap + "ОМ"}
        for f in forms:
            out[f] = code
    return out


def _stem_match(tok: str, stem: str) -> bool:
    if stem.endswith("$"):
        return tok == stem[:-1]
    if tok.startswith(stem):
        return True
    # опечатки OCR — только для длинных основ, чтобы «ОМСК» не путался с «ТОМСК»
    return len(stem) >= 7 and len(tok) >= len(stem) and fuzz.ratio(tok[:len(stem)], stem) >= 88


def _is_region_type(tok: str) -> bool:
    return tok in REGION_TYPE_EXACT or tok.startswith(REGION_TYPE_PREFIX)


def regions_in_text(text: str) -> set[str]:
    """Коды субъектов, названных в тексте «кем выдан»."""
    toks = tokens(text)
    found: set[str] = set()
    cities = _city_forms()
    for i, t in enumerate(toks):
        for stem, code in ANYWHERE:
            if t.startswith(stem):
                found.add(code)
        if i > 0 and toks[i - 1] in CITY_PREFIX and t in cities:
            found.add(cities[t])
        if _is_region_type(t):
            # «ОМСКОЙ ОБЛ.», «ПЕРМСКОМУ КРАЮ» — название перед типом; «РЕСПУБЛИКЕ ТАТАРСТАН» — и после.
            # Слово после «ОБЛ.» не берём: «… ОМСКОЙ ОБЛ. В КИРОВСКОМ АДМ. ОКРУГЕ» — не Кировская обл.
            near = toks[max(0, i - 1):i] + (toks[i + 1:i + 3] if t.startswith("РЕСП") else [])
            for code, (_, stems, _) in REGIONS.items():
                if any(_stem_match(n, s) for n in near for s in stems if not _is_region_type(n)):
                    found.add(code)
    return found


@lru_cache(maxsize=4096)
def _known_word(w: str) -> bool:
    return any(p.is_known for p in _morph.parse(w.lower()))


def correct_ocr(text: str) -> tuple[str, list[str]]:
    """Правит явные опечатки OCR в словах названия органа («РООСИИ» → «РОССИИ»).
    Слово меняется, только если его нет в словаре русского языка и оно очень похоже на одно слово бланка."""
    fixes = []
    text = (text or "").upper().replace("Ё", "Е")

    def repl(m: re.Match) -> str:
        w = m.group(0)
        prev = TOKEN_RE.findall(text[:m.start()])[-1:] or [""]
        # «МОСКОВСКОЙ ВЛАСТИ» → «МОСКОВСКОЙ ОБЛАСТИ»: после названия региона это может быть только «область»,
        # даже если OCR дал словарное слово
        if (re.search(r"[СЦЗ]КОЙ$", prev[0]) and w not in VOCAB
                and Levenshtein.distance(w, "ОБЛАСТИ") <= 2 and len(w) >= 5):
            fixes.append(f"{w} → ОБЛАСТИ")
            return "ОБЛАСТИ"
        if len(w) < 5 or w in VOCAB or _known_word(w):
            return w
        limit = 1 if len(w) < 9 else 2   # «ОСИНСКОМ» не должен стать «ОМСКОМ»: правим только 1–2 буквы
        cands = sorted((Levenshtein.distance(w, v), v) for v in VOCAB if abs(len(v) - len(w)) <= limit)
        cands = [(d, v) for d, v in cands if d <= limit]
        if cands and (len(cands) == 1 or cands[1][0] > cands[0][0]):
            fixes.append(f"{w} → {cands[0][1]}")
            return cands[0][1]
        return w

    out = TOKEN_RE.sub(repl, text)
    return out, fixes


def vocab_share(text: str) -> float:
    """Доля слов текста, которые встречаются в названиях органов (для выбора лучшего прочтения OCR)."""
    toks = [t for t in tokens(text) if len(t) >= 2]
    if not toks:
        return 0.0
    return sum(1 for t in toks if t in VOCAB) / len(toks)


def looks_like_authority(text: str) -> bool:
    return any(t in AUTHORITY_WORDS for t in tokens(text))
